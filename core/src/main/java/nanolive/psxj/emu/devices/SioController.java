    public void setBeamPositionSource(BeamPositionSource source) {
        beamPositionSource = source;
        refreshLightgunSampling();
        if (source == null && lightgunIrqLineActive) {
            lightgunIrqLineActive = false;
            interruptController.clear(10);
        }
    }

    public void attachMemoryCards(Path slot1Path, Path slot2Path) throws IOException {
        flush();
        MemoryCard nextSlot1 = slot1Path == null ? null : MemoryCard.openOrCreate(slot1Path);
        MemoryCard nextSlot2 = slot2Path == null ? null : MemoryCard.openOrCreate(slot2Path);
        slot1 = nextSlot1;
        slot2 = nextSlot2;
        if (slot1 != null) {
            Log.info("Attached memory card slot1: " + slot1Path);
        }
        if (slot2 != null) {
            Log.info("Attached memory card slot2: " + slot2Path);
        }
    }

